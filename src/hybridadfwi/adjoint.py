"""An external, first-order discrete adjoint for upstream ADFWI's FD8 PML.

The original ``ElasticPropagator.forward`` and native scripted step kernel
perform the forward simulation. The checkpoint callback is temporarily replaced
so no time-stepping autograd graph is built. Checkpoint mode replays native
segments. Full-history mode runs a compiled copy of the same numerical loop,
instrumented only to save five fields per time step, and performs no replay.
Both explicitly transpose the native discrete updates. One final VJP through
the static, model-sized material map produces Vp/Vs/rho gradients. No vendor
source files are changed.

This adapter targets ADFWI bv1.1, commit
559f581149343b1ed3dd2168caae595690bd601d, isotropic FD8 with split PML.
Sources, damping profiles, geometry and boundary choices are held fixed, as in
the upstream gradient.  Second derivatives and source gradients are unsupported.
The scoped module hooks serialize calls made through this adapter; unrelated
threads must not call the same upstream module concurrently.
"""

from contextlib import contextmanager
from dataclasses import dataclass, field
import ast
from functools import lru_cache
import hashlib
import importlib
import importlib.util
from pathlib import Path
import sys
import threading
import time
from typing import Dict, Mapping, Optional

import torch
from torch import Tensor
import torch.nn.functional as F

COMPONENTS = ("txx", "tzz", "txz", "vx", "vz")
MATERIAL_INDICES = tuple(range(20, 28))
STATE_START, STATE_END = 28, 43
_HOOK_LOCK = threading.RLock()


def _kernels():
    return importlib.import_module("ADFWI.propagator.elastic_kernels")


def _dtype_preserving_pad(data, pml, fs_offset, free_surface=True, device=None):
    """Upstream replicate padding, preserving the incoming material dtype."""
    top = fs_offset if free_surface else fs_offset + pml
    if device is not None:
        data = data.to(device)
    return F.pad(data[None, None], (pml, pml, top, pml), mode="replicate")[0, 0]


@contextmanager
def preserve_padding_dtype():
    """Apply the same external float64 padding correction to either method.

    Upstream allocates its padded coefficients with default-dtype ``zeros``.
    This hook prevents a silent float64-to-float32 material conversion.  Native
    FD constants are still generated by upstream DiffCoef in float32; neither
    their values nor the native step implementation are changed.
    """
    km = _kernels()
    with _HOOK_LOCK:
        original = km.pad_torchSingle
        km.pad_torchSingle = _dtype_preserving_pad
        try:
            yield
        finally:
            km.pad_torchSingle = original


@contextmanager
def disable_native_checkpointing():
    """Call native segments directly, so ordinary AD stores their full graph.

    ``checkpoint_segments=1`` alone still invokes PyTorch's checkpoint Function
    in upstream ADFWI. This scoped callback bypass is the actual off switch.
    It only removes options consumed by ``torch.utils.checkpoint.checkpoint``;
    all native positional arguments pass through unchanged.
    """
    km = _kernels()
    with _HOOK_LOCK:
        original = km.checkpoint

        def direct(function, *args, **kwargs):
            allowed = {"use_reentrant", "preserve_rng_state", "context_fn", "determinism_check", "debug"}
            unknown = set(kwargs) - allowed
            if unknown:
                raise TypeError(f"Unexpected native checkpoint options: {sorted(unknown)}")
            return function(*args)

        km.checkpoint = direct
        try:
            yield
        finally:
            km.checkpoint = original


@lru_cache(maxsize=1)
def _full_history_step():
    """Compile the pinned native loop with five history writes added per step.

    The numerical AST is reused verbatim. Only history-buffer initialization,
    field copies and extra return values are inserted. No step is replayed and
    the time loop remains compiled TorchScript, rather than a Python loop.
    Generated source is a local cache; vendor source remains unchanged.
    """
    from .experiment import ROOT, verify_upstream
    verify_upstream()
    km = _kernels()
    source_path = Path(km.__file__)
    source = source_path.read_text()
    tree = ast.parse(source)
    functions = [node for node in tree.body if isinstance(node, ast.FunctionDef)
                 and node.name == "step_forward_PML_8order"]
    if len(functions) != 1:
        raise RuntimeError("Expected one pinned native FD8 function")
    function = functions[0]
    function.name = "step_forward_PML_8order_full_history"
    function.decorator_list = ast.parse("@torch.jit.script\ndef unused():\n    pass\n").body[0].decorator_list
    loops = [node for node in function.body if isinstance(node, ast.For)
             and isinstance(node.target, ast.Name) and node.target.id == "t"]
    if len(loops) != 1:
        raise RuntimeError("Native FD8 time-loop structure changed")
    loop = loops[0]
    histories = ("history_vx", "history_vz", "history_txx", "history_tzz", "history_txz")
    initializers = ast.parse("\n".join(
        name + " = torch.empty((nt, src_n, nz_pml, nx_pml), dtype=dtype, device=device)"
        for name in histories)).body
    position = function.body.index(loop)
    function.body[position:position] = initializers
    # The native function updates velocity totals in-place later in this loop.
    # Preserve pre-update velocities before those writes happen.
    loop.body[:0] = ast.parse("history_vx[t].copy_(vx)\nhistory_vz[t].copy_(vz)").body
    # Stress totals are unchanged after their free-surface projection; retaining
    # them at loop end gives the fields used by the native velocity update.
    loop.body.extend(ast.parse("history_txx[t].copy_(txx)\nhistory_tzz[t].copy_(tzz)\nhistory_txz[t].copy_(txz)").body)
    returns = [node for node in function.body if isinstance(node, ast.Return)]
    if len(returns) != 1 or not isinstance(returns[0].value, ast.Tuple) or len(returns[0].value.elts) != 25:
        raise RuntimeError("Native FD8 return signature changed")
    returns[0].value.elts.extend(ast.Name(id=name, ctx=ast.Load()) for name in histories)
    ast.fix_missing_locations(function)
    generated = ("from typing import List\nimport torch\nfrom torch import Tensor\n"
                 "from ADFWI.propagator.elastic_kernels import DiffCoef, Dxfm_8, Dzfm_8, Dxbm_8, Dzbm_8\n\n"
                 + ast.unparse(function) + "\n")
    digest = hashlib.sha256(generated.encode()).hexdigest()
    cache = ROOT / ".cache" / "generated"
    cache.mkdir(parents=True, exist_ok=True)
    path = cache / ("fd8_full_history_" + digest + ".py")
    if not path.exists() or path.read_text() != generated:
        temporary = path.with_suffix(".tmp")
        temporary.write_text(generated)
        temporary.replace(path)
    name = "_hybridadfwi_fd8_full_history_" + digest
    spec = importlib.util.spec_from_file_location(name, path)
    module = importlib.util.module_from_spec(spec)
    sys.modules[name] = module
    spec.loader.exec_module(module)
    return module.step_forward_PML_8order_full_history, digest


def _synchronize(device):
    device = torch.device(device)
    if device.type == "cuda":
        torch.cuda.synchronize(device)
    elif device.type == "mps":
        torch.mps.synchronize()


def _derivative(value, coefficients, operator, radius=4):
    h, w = value.shape[-2:]
    result = value.new_zeros((value.shape[0], h - 2 * radius, w - 2 * radius))
    for k, c in enumerate(coefficients):
        if operator == "xf":
            result += c * (value[:, radius:h-radius, radius+k+1:w-radius+k+1]
                           - value[:, radius:h-radius, radius-k:w-radius-k])
        elif operator == "xb":
            result += c * (value[:, radius:h-radius, radius+k:w-radius+k]
                           - value[:, radius:h-radius, radius-k-1:w-radius-k-1])
        elif operator == "zf":
            result += c * (value[:, radius+k+1:h-radius+k+1, radius:w-radius]
                           - value[:, radius-k:h-radius-k, radius:w-radius])
        elif operator == "zb":
            result += c * (value[:, radius+k:h-radius+k, radius:w-radius]
                           - value[:, radius-k-1:h-radius-k-1, radius:w-radius])
        else:
            raise ValueError(operator)
    return result


def _derivative_transpose(value, shape, coefficients, operator, radius=4):
    h, w = shape[-2:]
    result = value.new_zeros(shape)
    for k, c in enumerate(coefficients):
        if operator == "xf":
            result[:, radius:h-radius, radius+k+1:w-radius+k+1] += c * value
            result[:, radius:h-radius, radius-k:w-radius-k] -= c * value
        elif operator == "xb":
            result[:, radius:h-radius, radius+k:w-radius+k] += c * value
            result[:, radius:h-radius, radius-k-1:w-radius-k-1] -= c * value
        elif operator == "zf":
            result[:, radius+k+1:h-radius+k+1, radius:w-radius] += c * value
            result[:, radius-k:h-radius-k, radius:w-radius] -= c * value
        elif operator == "zb":
            result[:, radius+k:h-radius+k, radius:w-radius] += c * value
            result[:, radius-k-1:h-radius-k-1, radius:w-radius] -= c * value
        else:
            raise ValueError(operator)
    return result


def _velocity_boundary_transpose(vx_bar, vz_bar, radius=4):
    """Transpose the three sequential FD8 surface assignments, last first."""
    h = radius + 1
    j = slice(radius, -radius)
    jp = slice(radius + 1, -radius + 1)
    q = vz_bar[:, h-3, j].clone()
    vz_bar[:, h-3, j] = 0
    vz_bar[:, h-2, j] += q
    q = vx_bar[:, h-2, j].clone()
    vx_bar[:, h-2, j] = 0
    vz_bar[:, h-2, jp] += q
    vz_bar[:, h-2, j] -= q
    vz_bar[:, h-1, jp] += q
    vz_bar[:, h-1, j] -= q
    vx_bar[:, h, j] += q
    q = vz_bar[:, h-2, j].clone()
    vz_bar[:, h-2, j] = 0
    vz_bar[:, h-1, j] += q


def _stress_boundary_transpose(tzz_bar, txz_bar, radius=4):
    h = radius + 1
    txz_bar[:, h, :] -= txz_bar[:, h-3, :]
    txz_bar[:, h-3, :] = 0
    txz_bar[:, h-1, :] -= txz_bar[:, h-2, :]
    txz_bar[:, h-2, :] = 0
    tzz_bar[:, h, :] -= tzz_bar[:, h-2, :]
    tzz_bar[:, h-2, :] = 0
    tzz_bar[:, h-1, :] = 0


def _receiver_scatter(state_bar, source, rx, rz):
    # index_add also gives the correct transpose for repeated receiver locations.
    linear = rz * state_bar.shape[-1] + rx
    state_bar.flatten(1).index_add_(1, linear, source)


def _reverse_step(bars, old_vx, old_vz, stresses, args, coefficient_grads, coefficients):
    """Explicit VJP of the native FD8 split-PML update (no AD operations)."""
    free_surface, dx, dz, dt = args[1], args[4], args[5], args[10]
    # Upstream staggered material arrays are one/two cells narrower than the
    # state arrays. Its ii/jj bounds come from state dimensions, not materials.
    height, width = old_vx.shape[-2:]
    interior = (slice(4, height - 4), slice(4, width - 4))
    state_interior = (slice(None), *interior)
    bcx, bcz = args[16][interior], args[17][interior]
    invx, invz = 1 / (1 + .5 * dt * bcx), 1 / (1 + .5 * dt * bcz)
    ax, az = (1 - .5 * dt * bcx) * invx, (1 - .5 * dt * bcz) * invz
    c11, c13, c15, c33, c35, c55, bx, bz = [args[i][interior] for i in MATERIAL_INDICES]
    shape = old_vx.shape

    # The total velocities are overwritten by the sum of the split states.
    vx_bar, vz_bar = bars[13], bars[14]
    if free_surface:
        _velocity_boundary_transpose(vx_bar, vz_bar)
    for k in (9, 10):
        bars[k] += vx_bar
    for k in (11, 12):
        bars[k] += vz_bar

    # Reverse velocity recurrences; outside the update rectangle is identity.
    total_stress_bars = [bars[k] for k in (6, 7, 8)]
    txx, tzz, txz = stresses
    velocity_rules = (
        (9, ax, invx, bx, 6, _derivative(txx, coefficients, "xf"), "xf", 0, dx),
        (10, az, invz, bx, 6, _derivative(txz, coefficients, "zb"), "zb", 2, dz),
        (11, ax, invx, bz, 7, _derivative(txz, coefficients, "xb"), "xb", 2, dx),
        (12, az, invz, bz, 7, _derivative(tzz, coefficients, "zf"), "zf", 1, dz),
    )
    for state, decay, inv, buoyancy, material, derivative, operator, target, spacing in velocity_rules:
        drive_bar = bars[state][state_interior] * (dt * inv / spacing)
        coefficient_grads[material][interior] += (drive_bar * derivative).sum(0)
        total_stress_bars[target] += _derivative_transpose(
            drive_bar * buoyancy, shape, coefficients, operator)
        bars[state][state_interior] *= decay

    if free_surface:
        _stress_boundary_transpose(total_stress_bars[1], total_stress_bars[2])
    for total, pair in zip(total_stress_bars, ((0, 1), (2, 3), (4, 5))):
        for k in pair:
            bars[k] += total

    # The source is an additive constant, then stress totals are overwritten.
    # Each stress drive is a sum of two material-weighted velocity derivatives.
    derivatives = {
        ("vx", op): _derivative(old_vx, coefficients, op)
        for op in ("xb", "zb", "xf", "zf")
    }
    derivatives.update({
        ("vz", op): _derivative(old_vz, coefficients, op)
        for op in ("xb", "zb", "xf", "zf")
    })
    vx_input_bar, vz_input_bar = torch.zeros_like(old_vx), torch.zeros_like(old_vz)
    stress_rules = (
        (0, ax, invx, dx, ((0, c11, "vx", "xb"), (2, c15, "vz", "xb"))),
        (1, az, invz, dz, ((2, c15, "vx", "zb"), (1, c13, "vz", "zb"))),
        (2, ax, invx, dx, ((1, c13, "vx", "xb"), (4, c35, "vz", "xb"))),
        (3, az, invz, dz, ((4, c35, "vx", "zb"), (3, c33, "vz", "zb"))),
        (4, ax, invx, dx, ((2, c15, "vx", "xf"), (5, c55, "vz", "xf"))),
        (5, az, invz, dz, ((5, c55, "vx", "zf"), (4, c35, "vz", "zf"))),
    )
    for state, decay, inv, spacing, terms in stress_rules:
        drive_bar = bars[state][state_interior] * (dt * inv / spacing)
        for material, value, component, operator in terms:
            coefficient_grads[material][interior] += (
                drive_bar * derivatives[(component, operator)]).sum(0)
            target = vx_input_bar if component == "vx" else vz_input_bar
            target += _derivative_transpose(drive_bar * value, shape, coefficients, operator)
        bars[state][state_interior] *= decay
    for k in (6, 7, 8):
        bars[k].zero_()
    bars[13], bars[14] = vx_input_bar, vz_input_bar


@dataclass
class AdjointTape:
    """Forward metadata/history plus a single-use static-material VJP.

    ``backward`` returns a dict of raw gradients for trainable ``vp``, ``vs``,
    and/or ``rho``.  It does not assign ``parameter.grad`` or apply processing.
    """
    model: object
    segments: list
    material_tensors: tuple
    step: object
    output_shape: tuple
    stats: dict = field(default_factory=dict)
    full_history: Optional[list] = None
    _consumed: bool = False

    def backward(self, data_vjp: Mapping[str, Tensor]) -> Dict[str, Tensor]:
        if self._consumed:
            raise RuntimeError("AdjointTape is single-use; run a new forward first")
        unknown = set(data_vjp) - set(COMPONENTS)
        if unknown:
            raise ValueError(f"Unknown receiver components: {sorted(unknown)}")
        for key, source in data_vjp.items():
            if tuple(source.shape) != self.output_shape:
                raise ValueError(f"{key} VJP shape {tuple(source.shape)} != {self.output_shape}")
        if not self.segments:
            raise RuntimeError("No native forward metadata were captured")
        self._consumed = True
        km = _kernels()
        args0 = self.segments[0][1]
        template = self.full_history[0][0] if self.full_history is not None else args0[28]
        coefficients = km.DiffCoef(4, "s").to(template.device)
        parameter_names = [name for name in ("vp", "vs", "rho")
                           if getattr(self.model, name).requires_grad]
        parameters = [getattr(self.model, name) for name in parameter_names]
        if not parameters:
            raise ValueError("At least one of vp, vs, rho must require gradients")
        replay_s = reverse_s = 0.0
        max_history_steps = 0
        device = template.device
        with torch.no_grad():
            bars = ([torch.zeros_like(template) for _ in range(15)] if self.full_history is not None
                    else [torch.zeros_like(value) for value in args0[STATE_START:STATE_END]])
            del template
            coefficient_grads = [torch.zeros_like(args0[i]) for i in MATERIAL_INDICES]
            for start, args in reversed(self.segments):
                steps = args[11].shape[-1]
                if self.full_history is None:
                    _synchronize(device)
                    timer = time.perf_counter()
                    states = args[STATE_START:STATE_END]
                    histories = []
                    for t in range(steps):
                        old_vx, old_vz = states[13], states[14]
                        one_args = (*args[:11], args[11][..., t:t+1], *args[12:STATE_START],
                                    *states, *args[STATE_END:])
                        result = self.step(*one_args)
                        states = result[:15]
                        histories.append((old_vx, old_vz, states[6:9]))
                    _synchronize(device)
                    replay_s += time.perf_counter() - timer
                else:
                    histories = self.full_history
                    if len(histories) != steps:
                        raise RuntimeError("Saved full history length does not match the original forward")
                max_history_steps = max(max_history_steps, len(histories))
                timer = time.perf_counter()
                for t in range(steps - 1, -1, -1):
                    for component, state in zip(COMPONENTS, (6, 7, 8, 13, 14)):
                        if component in data_vjp:
                            _receiver_scatter(bars[state], data_vjp[component][:, start+t],
                                              args[13], args[14])
                    old_vx, old_vz, stress = histories.pop()
                    _reverse_step(bars, old_vx, old_vz, stress, args, coefficient_grads, coefficients)
                _synchronize(device)
                reverse_s += time.perf_counter() - timer
            # The saved per-time tensors are views into five contiguous history
            # buffers. Drop the last iteration's references before material AD.
            del old_vx, old_vz, stress
        # This is the only autograd.grad inside the adapter: a static material
        # mapping, whose graph/storage does not grow with propagation duration.
        _synchronize(device)
        timer = time.perf_counter()
        active = [(value, gradient) for value, gradient in
                  zip(self.material_tensors, coefficient_grads) if value.requires_grad]
        with torch.enable_grad():
            if active:
                gradients = torch.autograd.grad(
                    tuple(value for value, _ in active), parameters,
                    grad_outputs=tuple(gradient for _, gradient in active),
                    allow_unused=True, create_graph=False)
            else:
                gradients = (None,) * len(parameters)
        _synchronize(device)
        self.stats.update(replay_seconds=replay_s, adjoint_seconds=reverse_s,
                          static_material_vjp_seconds=time.perf_counter()-timer,
                          peak_history_steps=max_history_steps,
                          temporal_autograd=False, static_material_autograd=True)
        self.segments.clear()
        self.material_tensors = ()
        if self.full_history is not None:
            self.full_history.clear()
        return {name: torch.zeros_like(parameter) if gradient is None else gradient.detach()
                for name, parameter, gradient in zip(parameter_names, parameters, gradients)}


def hybrid_forward(propagator, fd_order=8, checkpoint_segments=1, shot_index=None, *, checkpointing=True):
    """Run unmodified upstream forward and capture a no-time-graph adjoint tape.

    This applies ``preserve_padding_dtype`` internally; use the same context
    around the baseline for a matched float64 experiment. Data VJPs are computed
    outside this function, e.g.
    ``leaf = output['vz'].detach().requires_grad_(); source = grad(loss(leaf),leaf)``.
    The parameter flags must remain enabled: they identify the desired static
    material-map VJP, while native temporal operations execute under no_grad.

    With ``checkpointing=False`` use ``checkpoint_segments=1``: a compiled
    instrumented copy of the exact native numerical loop saves five fields per
    time step during this original forward. The reverse consumes those fields
    directly, with zero temporal checkpoints and zero forward replay.
    """
    if fd_order != 8:
        raise NotImplementedError("This audited adapter currently supports FD8 only")
    if str(propagator.abc_type).lower() != "pml":
        raise NotImplementedError("This audited adapter supports split PML only")
    if not isinstance(checkpoint_segments, int) or checkpoint_segments < 1:
        raise ValueError("checkpoint_segments must be a positive integer")
    if not checkpointing and checkpoint_segments != 1:
        raise ValueError("No-checkpoint mode requires checkpoint_segments=1")
    km = _kernels()
    segments, material_tensors, position, step_function = [], (), 0, None
    full_history = None
    instrumented_digest = None
    instrumented_step = None
    if not checkpointing:
        with _HOOK_LOCK:
            instrumented_step, instrumented_digest = _full_history_step()

    def capture(function, *args, **kwargs):
        nonlocal material_tensors, position, step_function, full_history
        if len(args) != 45:
            raise RuntimeError(f"Native step signature changed: expected 45 arguments, got {len(args)}")
        if int(args[0]) != 8:
            raise RuntimeError("Captured a non-FD8 step")
        if not material_tensors:
            material_tensors = tuple(args[i] for i in MATERIAL_INDICES)
            step_function = function
        # Native step clones all input states before its in-place updates.
        # Keeping detached references therefore retains immutable checkpoints.
        detached = tuple(value.detach() if torch.is_tensor(value) else value for value in args)
        if not checkpointing:
            if segments:
                raise RuntimeError("No-checkpoint mode must execute one complete native time loop")
            with torch.no_grad():
                result = instrumented_step(*detached)
            vx, vz, txx, tzz, txz = result[25:]
            full_history = [(x, z, (xx, zz, xz)) for x, z, xx, zz, xz in zip(vx, vz, txx, tzz, txz)]
            if len(full_history) != args[11].shape[-1]:
                raise RuntimeError("Instrumented forward did not save every time step")
            # Initial states are not retained or reconstructed in this mode;
            # zero adjoint state shapes/devices come from the full history.
            metadata = (*detached[:STATE_START], *((None,) * 15), *detached[STATE_END:])
            segments.append((0, metadata))
            position += args[11].shape[-1]
            return result[:25]
        segments.append((position, detached))
        position += args[11].shape[-1]
        with torch.no_grad():
            return function(*detached)

    with _HOOK_LOCK, preserve_padding_dtype():
        original = km.checkpoint
        km.checkpoint = capture
        try:
            # Only model-sized coefficient preparation is traced; capture()
            # suppresses AD for every native time-propagation segment.
            with torch.enable_grad():
                output = propagator.forward(shot_index=shot_index, fd_order=fd_order,
                                            checkpoint_segments=checkpoint_segments)
        finally:
            km.checkpoint = original
    if any(output[name].requires_grad for name in COMPONENTS):
        raise RuntimeError("Native hybrid receiver data unexpectedly has an autograd graph")
    tape = AdjointTape(propagator.model, segments, material_tensors, step_function,
                       tuple(output["vz"].shape),
                       {"checkpointing": bool(checkpointing),
                        "checkpoint_segments": len(segments) if checkpointing else 0,
                        "checkpoint_state_tensors": 15 * len(segments) if checkpointing else 0,
                        "saved_history_steps": 0 if checkpointing else position,
                        "saved_history_fields_per_step": 0 if checkpointing else 5,
                        "instrumented_native_source_sha256": instrumented_digest,
                        "temporal_autograd": False},
                       full_history=full_history)
    return output, tape
